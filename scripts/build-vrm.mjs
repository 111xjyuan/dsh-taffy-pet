import { build } from 'esbuild'
import { fileURLToPath } from 'node:url'
import path from 'node:path'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const out = path.join(root, 'lib', 'vrm-runtime.js')

const result = await build({
  entryPoints: [path.join(root, 'src', 'vrm-entry.js')],
  bundle: true,
  format: 'iife',
  globalName: 'TaffyVRMBundle',
  target: ['chrome110'],
  minify: true,
  legalComments: 'none',
  write: false,
  define: { 'process.env.NODE_ENV': '"production"' },
})

const code = result.outputFiles[0].text
const banner = '/* generated by scripts/build-vrm.mjs — three.js + @pixiv/three-vrm */\n'
const { writeFileSync, mkdirSync } = await import('node:fs')
mkdirSync(path.dirname(out), { recursive: true })
writeFileSync(out, banner + code)
console.log('wrote', out, (code.length / 1024).toFixed(0) + 'KB')
